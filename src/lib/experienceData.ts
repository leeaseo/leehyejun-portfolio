export function getHonorSlug(title: string, index?: number): string {
  const t = (title || '').toLowerCase();
  if (t.includes('poing')) return 'poing-asia-design-prize';
  if (t.includes('como') || t.includes('고지베리')) return 'como-desk-gojiberry';
  if (t.includes('librat') || t.includes('miicon') || t.includes('콘크리트')) return 'librat-miicorn-concrete';
  if (t.includes('convenset') || t.includes('건조대')) return 'convenset-drying-storage';
  if (index !== undefined) {
    const fallbacks = [
      'poing-asia-design-prize',
      'como-desk-gojiberry',
      'librat-miicorn-concrete',
      'convenset-drying-storage',
    ];
    if (fallbacks[index]) return fallbacks[index];
  }
  return 'poing-asia-design-prize';
}
