export function getHonorSlug(title: string, index: number = 0): string {
  const lower = (title || '').toLowerCase();
  if (lower.includes('poing') || lower.includes('asia design') || lower.includes('골드') || lower.includes('gold')) {
    return 'poing-asia-design-prize';
  }
  if (lower.includes('como') || lower.includes('고지베리') || lower.includes('데스크') || lower.includes('desk')) {
    return 'como-desk-gojiberry';
  }
  if (lower.includes('librat') || lower.includes('miicorn') || lower.includes('콘크리트')) {
    return 'librat-miicorn-concrete';
  }
  return `experience-${index + 1}`;
}

